#!/usr/bin/env python3
"""Create compact, reproducible benchmark evidence from raw result JSON."""
from __future__ import annotations

import argparse
import hashlib
import json
import statistics
from pathlib import Path


def summarize(path: Path) -> dict:
    raw = json.loads(path.read_text(encoding="utf-8"))
    result = {k: v for k, v in raw.items() if k not in {"runs", "samples"}}
    result["source"] = {"file": path.name, "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
    result["runs"] = []
    for raw_run in raw.get("runs", []):
        run = {k: v for k, v in raw_run.items() if k != "assets"}
        warm = [s["elapsedMs"] for s in raw_run.get("stages", [])
                if str(s.get("name", "")).startswith("warm-repeat") and s.get("elapsedMs") is not None]
        run["derived"] = {
            "warmMedianMs": statistics.median(warm) if warm else None,
            "warmRangeMs": [min(warm), max(warm)] if warm else None,
            "unsupportedCount": len(raw_run.get("unsupported", [])),
        }
        result["runs"].append(run)
    return result


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", type=Path, required=True)
    ap.add_argument("--negative-output", type=Path)
    ap.add_argument("--negative-input", type=Path)
    ap.add_argument("inputs", nargs="+", type=Path)
    args = ap.parse_args()
    engines = {p.stem.split("-minimal")[0]: summarize(p) for p in args.inputs}
    payload = {"generator": "summarize-results.py", "corpus": {"total": 122, "supported": 3, "unsupported": 119}, "engines": engines}
    args.output.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    rows = []
    for browser, data in engines.items():
        for run in data["runs"]:
            uss = run.get("memoryMeasurement", {}).get("uss", {})
            cache = run.get("cache", {})
            ready = next((s["atMs"] for s in run.get("stages", []) if s.get("stage") == "ready-to-verify"), float("nan"))
            warm = run["derived"]["warmMedianMs"] or float("nan")
            lo, hi = run["derived"]["warmRangeMs"] or (float("nan"), float("nan"))
            present = cache.get('entries', 0)
            expected = present + len(cache.get('missing', []))
            rows.append(f"| {browser} | {run.get('runKind','')} | {ready:.1f} | {warm:.1f} / {lo:.1f}–{hi:.1f} | {data.get('baselineMemory',{}).get('uss',0):,} | {uss.get('incrementalPeak',0):,} / {uss.get('incrementalSteady',0):,} | {run.get('httpResponseBodyBytes',0):,} | {run.get('memory',{}).get('heapBytes',0):,} | {data.get('profileLogicalFileBytes',0):,} | {'writable' if run.get('cacheWritable',True) else 'not writable'}; {present}/{expected}; {cache.get('bodyBytes',0):,} B |")
    table = "# Minimal-reference benchmark evidence\n\nGenerated by `summarize-results.py` from raw JSON. The corpus is explicitly 3/122 supported and 119/122 unsupported; this is not a full-curriculum claim.\n\n| Engine | Run kind | Ready ms | Warm median / range ms | Baseline USS | Incremental USS peak / steady | HTTP body bytes | Logical heap | Profile logical bytes | Cache |\n|---|---|---:|---:|---:|---:|---:|---:|---:|---|\n" + "\n".join(rows) + "\n\nThe JSON retains full per-run proof records, including audit/output, errors, axioms, substitutions, certificates, and source hashes, while omitting only repetitive asset lists and top-level process samples. WebKit is desktop Playwright on Windows, not a physical iPhone; its cache was non-writable at 0 bytes and 128 trial timed out. Measurements are localhost-only without network throttling; concurrent WSL compilation may affect latency.\n"
    args.output.with_name("metrics-table.md").write_text(table, encoding="utf-8")
    if args.negative_output and args.negative_input:
        negative = {"generator": "summarize-results.py", "negativeTrial": summarize(args.negative_input)}
        args.negative_output.write_text(json.dumps(negative, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
