class UniqueLoader(yaml.SafeLoader):
    def construct_mapping(self,node,deep=False):
        self.flatten_mapping(node);result={}
        for k,v in node.value:
            key=self.construct_object(k,deep=deep)
            if key in result:raise ValueError(f'Duplicate YAML key: {key}')
            result[key]=self.construct_object(v,deep=deep)
        return result

def sources():
    folder=ROOT/'content/math/algebra_foundations/skills'
    return [yaml.load(next(folder.glob(id+'_*.yaml')).read_text(encoding='utf-8'),Loader=UniqueLoader) for id in IDS]

def test_native_source_and_review_preview_agree():
    by_id={s['id']:s for s in DATA['skills']}
    for source in sources():
        assert str(source['schema_version'])=='0.2'
        built=by_id[source['id']]
        for key,value in source.items():
            if key not in ('test','schema_version'):assert value==built[key],(source['id'],key)
        assert source['test']['question_count']==built['question_count']==(21 if source['id'] in {'MATH_FUNC_004','MATH_FUNC_007','MATH_CALC_001','MATH_CALC_002'} else 20)
        assert source['test']['randomize_order'] is built['native_randomize_order'] is True
        assert source['test']['questions']==built['native_templates']


def test_metadata_graph_and_taxonomy_are_complete():
    track=yaml.load((ROOT/'content/math/algebra_foundations/track.yaml').read_text(),Loader=UniqueLoader)
